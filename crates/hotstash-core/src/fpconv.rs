const FRAC_MASK: u64 = 0x000F_FFFF_FFFF_FFFF;
const EXP_MASK: u64 = 0x7FF0_0000_0000_0000;
const HIDDEN_BIT: u64 = 0x0010_0000_0000_0000;
const SIGN_MASK: u64 = 0x8000_0000_0000_0000;
const EXP_BIAS: i32 = 1023 + 52;

