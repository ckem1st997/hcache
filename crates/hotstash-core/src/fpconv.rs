fn find_cachedpow10(exp: i32) -> (Fp, i32) {
    const ONE_LOG_TEN: f64 = 0.30102999566398114;
    let approx = (f64::from(-(exp + NPOWERS)) * ONE_LOG_TEN) as i32;
    let mut idx = (approx - FIRSTPOWER) / STEPPOWERS;
    loop {
        let current = exp + POWERS_TEN[idx as usize].exp + 64;
        if current < EXPMIN {
            idx += 1;
            continue;
        }
        if current > EXPMAX {
            idx -= 1;
            continue;
        }
        return (POWERS_TEN[idx as usize], FIRSTPOWER + idx * STEPPOWERS);
    }
}

fn build_fp(d: f64) -> Fp {
    let bits = d.to_bits();
    let mut fp = Fp {
        frac: bits & FRAC_MASK,
        exp: ((bits & EXP_MASK) >> 52) as i32,
    };
    if fp.exp != 0 {
        fp.frac += HIDDEN_BIT;
        fp.exp -= EXP_BIAS;
    } else {
        fp.exp = -EXP_BIAS + 1;
    }
    fp
}

fn normalize(fp: &mut Fp) {
    while fp.frac & HIDDEN_BIT == 0 {
        fp.frac <<= 1;
        fp.exp -= 1;
    }
    let shift = 64 - 52 - 1;
    fp.frac <<= shift;
    fp.exp -= shift;
}

/// The lower and upper boundaries of `fp`, at the upper one's exponent.
fn get_normalized_boundaries(fp: &Fp) -> (Fp, Fp) {
    let mut upper = Fp {
        frac: (fp.frac << 1) + 1,
        exp: fp.exp - 1,
    };
    while upper.frac & (HIDDEN_BIT << 1) == 0 {
        upper.frac <<= 1;
        upper.exp -= 1;
    }
    let u_shift = 64 - 52 - 2;
    upper.frac <<= u_shift;
    upper.exp -= u_shift;

    let l_shift = if fp.frac == HIDDEN_BIT { 2 } else { 1 };
    let mut lower = Fp {
        frac: (fp.frac << l_shift) - 1,
        exp: fp.exp - l_shift,
    };
    lower.frac <<= lower.exp - upper.exp;
    lower.exp = upper.exp;
    (lower, upper)
}

fn multiply(a: &Fp, b: &Fp) -> Fp {
    const LOMASK: u64 = 0x0000_0000_FFFF_FFFF;
    let ah_bl = (a.frac >> 32) * (b.frac & LOMASK);
    let al_bh = (a.frac & LOMASK) * (b.frac >> 32);
    let al_bl = (a.frac & LOMASK) * (b.frac & LOMASK);
    let ah_bh = (a.frac >> 32) * (b.frac >> 32);
    let mut tmp = (ah_bl & LOMASK) + (al_bh & LOMASK) + (al_bl >> 32);
    // round up
    tmp += 1 << 31;
    Fp {
        frac: ah_bh + (ah_bl >> 32) + (al_bh >> 32) + (tmp >> 32),
        exp: a.exp + b.exp + 64,
    }
}

fn round_digit(digits: &mut [u8], ndigits: usize, delta: u64, mut rem: u64, kappa: u64, frac: u64) {
    if ndigits == 0 {
        return;
    }
    while rem < frac
        && delta - rem >= kappa
        && (rem + kappa < frac || frac - rem > rem + kappa - frac)
    {
        digits[ndigits - 1] -= 1;
        rem += kappa;
    }
}

fn generate_digits(fp: &Fp, upper: &Fp, lower: &Fp, digits: &mut [u8], k: &mut i32) -> usize {
    let wfrac = upper.frac.wrapping_sub(fp.frac);
    let mut delta = upper.frac.wrapping_sub(lower.frac);

    let shift = -upper.exp;
    let one_frac = 1u64 << shift;

    let mut part1 = upper.frac >> shift;
    let mut part2 = upper.frac & (one_frac - 1);

    let mut idx = 0;
    let mut kappa = 10;
    // 1000000000
    let mut divp = 10;
    while kappa > 0 {
        let div = TENS[divp];
        let digit = part1 / div;
        if digit != 0 || idx != 0 {
            digits[idx] = digit as u8 + b'0';
            idx += 1;
        }
        part1 -= digit * div;
        kappa -= 1;

        let tmp = (part1 << shift).wrapping_add(part2);
        if tmp <= delta {
            *k += kappa;
            round_digit(digits, idx, delta, tmp, div << shift, wfrac);
            return idx;
        }
        divp += 1;
    }

    // 10
    let mut unit = 18;
    loop {
        part2 = part2.wrapping_mul(10);
        delta = delta.wrapping_mul(10);
        kappa -= 1;

        let digit = part2 >> shift;
        if digit != 0 || idx != 0 {
            digits[idx] = digit as u8 + b'0';
            idx += 1;
        }
        part2 &= one_frac - 1;
        if part2 < delta {
            *k += kappa;
            round_digit(
                digits,
                idx,
                delta,
                part2,
                one_frac,
                wfrac.wrapping_mul(TENS[unit]),
            );
            return idx;
        }
        unit -= 1;
    }
}

fn grisu2(d: f64, digits: &mut [u8], k: &mut i32) -> usize {
    let mut w = build_fp(d);
    let (lower, upper) = get_normalized_boundaries(&w);
    normalize(&mut w);

    let (cp, cached) = find_cachedpow10(upper.exp);
    let w = multiply(&w, &cp);
    let mut upper = multiply(&upper, &cp);
    let mut lower = multiply(&lower, &cp);
    lower.frac = lower.frac.wrapping_add(1);
    upper.frac = upper.frac.wrapping_sub(1);

    *k = -cached;
    generate_digits(&w, &upper, &lower, digits, k)
}

fn emit_digits(digits: &[u8], k: i32, neg: bool, dest: &mut Vec<u8>) {
    let mut ndigits = digits.len() as i32;
    let mut exp = (k + ndigits - 1).abs();

    // write plain integer
    if k >= 0 && exp < ndigits + 7 {
        dest.extend_from_slice(digits);
        dest.resize(dest.len() + k as usize, b'0');
        return;
    }

    // write decimal w/o scientific notation
    if k < 0 && (k > -7 || exp < 4) {
        let offset = ndigits - k.abs();
        if offset <= 0 {
            // fp < 1.0 -> write leading zero
            dest.extend_from_slice(b"0.");
            dest.resize(dest.len() + (-offset) as usize, b'0');
            dest.extend_from_slice(digits);
        } else {
            // fp > 1.0
            let (int, frac) = digits.split_at(offset as usize);
            dest.extend_from_slice(int);
            dest.push(b'.');
            dest.extend_from_slice(frac);
        }
        return;
    }

    // write decimal w/ scientific notation
    ndigits = ndigits.min(18 - i32::from(neg));
    dest.push(digits[0]);
    if ndigits > 1 {
        dest.push(b'.');
        dest.extend_from_slice(&digits[1..ndigits as usize]);
    }
    dest.push(b'e');
    dest.push(if k + ndigits - 1 < 0 { b'-' } else { b'+' });

    let mut cent = 0;
    if exp > 99 {
        cent = exp / 100;
        dest.push(cent as u8 + b'0');
        exp -= cent * 100;
    }
    if exp > 9 {
        let dec = exp / 10;
        dest.push(dec as u8 + b'0');
        exp -= dec * 10;
    } else if cent != 0 {
        dest.push(b'0');
    }
    dest.push((exp % 10) as u8 + b'0');
}

/// fpconv_dtoa: appends `d` to `dest`.
pub fn dtoa(d: f64, dest: &mut Vec<u8>) {
    let bits = d.to_bits();
    let neg = bits & SIGN_MASK != 0;
    if neg {
        dest.push(b'-');
    }

    // filter_special
    if d == 0.0 {
        dest.push(b'0');
        return;
    }
    if bits & EXP_MASK == EXP_MASK {
        dest.extend_from_slice(if bits & FRAC_MASK != 0 {
            b"nan"
        } else {
            b"inf"
        });
        return;
    }

    // Eighteen in fpconv; Grisu2 never writes that many.
    let mut digits = [0u8; 24];
    let mut k = 0;
    let ndigits = grisu2(d, &mut digits, &mut k);
    emit_digits(&digits[..ndigits], k, neg, dest);
}

#[cfg(test)]
mod tests {
    use super::*;

    fn text(d: f64) -> String {
        let mut out = Vec::new();
        dtoa(d, &mut out);
        String::from_utf8(out).unwrap()
    }

    #[test]
    fn prints_as_valkey() {
        assert_eq!(text(1e300), "1e+300");
        assert_eq!(text(1e21), "1e+21");
        assert_eq!(text(1.5e20), "1.5e+20");
        assert_eq!(text(1.5e7), "15000000");
        assert_eq!(text(123456789012345678.0), "123456789012345680");
        assert_eq!(text(0.1), "0.1");
        assert_eq!(text(1e-7), "1e-7");
        assert_eq!(text(0.0001), "0.0001");
        assert_eq!(text(-2.5), "-2.5");
        assert_eq!(text(123.456), "123.456");
        assert_eq!(text(-0.0), "-0");
        assert_eq!(text(f64::INFINITY), "inf");
        assert_eq!(text(f64::MAX), "1.7976931348623157e+308");
        assert_eq!(text(f64::MIN_POSITIVE), "2.2250738585072014e-308");
        assert_eq!(text(5e-324), "5e-324");
    }

    #[test]
    fn reads_back_the_same() {
        let mut x = 0x9E37_79B9_7F4A_7C15u64;
        for _ in 0..200_000 {
            x ^= x << 13;
            x ^= x >> 7;
            x ^= x << 17;
            let d = f64::from_bits(x);
            if !d.is_finite() {
                continue;
            }
            let t = text(d);
            assert_eq!(t.parse::<f64>().unwrap().to_bits(), d.to_bits(), "{t}");
        }
    }
}
